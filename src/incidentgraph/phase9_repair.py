class Selection(BaseModel):
    model_config = ConfigDict(extra="forbid")
    outcome: Literal["probable_cause", "inconclusive", "no_incident_detected"]
    component: Component
    mechanism: Mechanism
    supporting_refs: list[str] = Field(max_length=6)
    explanation: str = Field(min_length=3, max_length=500)
    limitation: str | None = Field(default=None, max_length=300)


class CompactSelection(BaseModel):
    """One semantic decision, eliminating contradictory independently generated fields."""

    model_config = ConfigDict(extra="forbid")
    decision: Mechanism
    evidence_refs: list[str] = Field(max_length=3)
    rationale: str = Field(min_length=3, max_length=240)

    def expanded(self) -> Selection:
        if self.decision == "insufficient_observation":
            outcome = "inconclusive"
            component = "none"
        elif self.decision in {"healthy", "healthy_high_traffic"}:
            outcome = "no_incident_detected"
            component = "none"
        else:
            outcome = "probable_cause"
            component = (
                "svc-checkout"
                if self.decision in {"database_pool_exhaustion", "deployment_regression"}
                else "svc-payments"
            )
        return Selection.model_validate(
            {
                "outcome": outcome,
                "component": component,
                "mechanism": self.decision,
                "supporting_refs": self.evidence_refs,
                "explanation": self.rationale,
                "limitation": self.rationale if outcome == "inconclusive" else None,
            }
        )


